// Read-only checks against a generated public-list fixture, not the iPad's cache.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {dirname, join} from 'node:path';
const path = process.argv[2];
assert(path, 'Pass the native JSON generated by make-native-adblock-fixture.mjs');
const rules = JSON.parse(fs.readFileSync(path, 'utf8'));
function decision(url, page = 'https://adblock-tester.com/', type = 'script', party = 'third-party', context = 'top-frame') {
    let result = 'none';
    for (const {trigger: t, action: a} of rules) {
        if (!new RegExp(t['url-filter'], t['url-filter-is-case-sensitive'] ? '' : 'i').test(url)) continue;
        if (t['resource-type'] && !t['resource-type'].includes(type)) continue;
        if (t['load-type'] && !t['load-type'].includes(party)) continue;
        if (t['load-context'] && !t['load-context'].includes(context)) continue;
        // A trigger's URL conditions are an intersection, not alternatives.
        if (['if-top-url', 'if-frame-url'].some(name => t[name] && !t[name].some(p => new RegExp(p).test(page)))) continue;
        if (['unless-top-url', 'unless-frame-url'].some(name => t[name] && t[name].some(p => new RegExp(p).test(page)))) continue;
        result = a.type;
    }
    return result;
}
const blockedURLs = [
    'https://www.googletagmanager.com/gtag/js?id=UA-20899801-10',
    'https://static.hotjar.com/c/hotjar-1639117.js?sv=6',
    'https://mc.yandex.ru/metrika/tag.js',
    'https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js',
    'https://pagead2.googleadservices.com/',
    'https://adtago.s3.amazonaws.com/',
    'https://pixel.facebook.com/',
    'https://analytics.s3.amazonaws.com/',
    'https://click.googleanalytics.com/',
];
for (const url of blockedURLs) assert.equal(decision(url), 'block', 'Expected a retained native block for ' + url);
const conversion = 'https://googleadservices.com/pagead/conversion_async.js';
assert.equal(decision(conversion, 'https://zubizu.com/'), 'ignore-previous-rules', 'Original site exception must survive');
assert.equal(decision(conversion), 'block', 'Site exception must not exempt every website');
assert.equal(decision('https://googleadservices.com/other.js', 'https://zubizu.com/'), 'block', 'Path exception must not exempt the entire host');
const facebook = 'https://pixel.facebook.com/ads/profile/';
assert.equal(decision(facebook, 'https://www.facebook.com/', 'raw'), 'ignore-previous-rules', 'Same-site Facebook API exception must survive');
assert.equal(decision(facebook, 'https://adblock-tester.com/', 'raw'), 'block', 'First-party exception must not permit a third-party test request');
const supplemental = [...fs.readFileSync('Browser/Utilities/NativeAdResourceRules.swift','utf8')
    .matchAll(/Entry\(host: "([^"]+)", firstPartySites: (\[[^\n]+\])\)/g)]
    .map(([,host,sites])=>({host,sites:JSON.parse(sites)}));
assert.equal(supplemental.length,14);
// Compare only the ordinary domain block prefix against the checkpoint. The
// new supplement slots and explicitly retained priority endpoints may replace
// a bounded number of sampled domains, but must not reshuffle the whole 20k set.
const plainDomainResources = ['script','image','style-sheet','font','media','raw'];
function hostFilter(host) {
 return '^https?://([^/:?#@]+\\.)?' + host.split('.').join('\\.') + '(:[0-9]+)?/';
}
const supplementalFilters = new Set(supplemental.map(({host}) => hostFilter(host)));
function leadingPlainDomainFilters(value) {
 const prefix = '^https?://([^/:?#@]+\\.)?';
 const suffix = '(:[0-9]+)?/';
 const result = [];
 for (const {trigger:t} of value) {
  const filter = t?.['url-filter'];
  const plain = typeof filter === 'string' && filter.startsWith(prefix) && filter.endsWith(suffix)
   && JSON.stringify(t['resource-type']) === JSON.stringify(plainDomainResources)
   && JSON.stringify(t['load-type']) === '["third-party"]'
   && JSON.stringify(t['load-context']) === '["top-frame"]'
   && !t['if-top-url'] && !t['unless-top-url'] && !supplementalFilters.has(filter);
  if (!plain) break;
  result.push(filter);
 }
 return new Set(result);
}
const baselinePath = join(dirname(path), 'baseline-native.json');
if (fs.existsSync(baselinePath)) {
 const baselineDomains = leadingPlainDomainFilters(JSON.parse(fs.readFileSync(baselinePath, 'utf8')));
 const currentDomains = leadingPlainDomainFilters(rules);
 const removed = [...baselineDomains].filter(filter => !currentDomains.has(filter));
 const added = [...currentDomains].filter(filter => !baselineDomains.has(filter));
 assert(removed.length <= 4, 'Unexpected ordinary-domain churn: removed ' + removed.length);
 assert(added.length <= 4, 'Unexpected ordinary-domain churn: added ' + added.length);
 console.log('PASS: ordinary-domain selection remains stable (removed ' + removed.length + ', added ' + added.length + '; bounded promoted/supplement replacements)');
}
const realScopedScript = rules.find(({trigger:t}) =>
 t['if-top-url']?.some(p => p.includes('spiegel\\.de')) &&
 t['url-filter']?.includes('google-analytics\\.com\\/analytics\\.js') &&
 t['resource-type']?.includes('script'));
assert(realScopedScript, 'Expected a retained real-list source-scoped script/path rule');
assert.equal(decision('https://google-analytics.com/analytics.js', 'https://www.spiegel.de/', 'script'), 'block', 'Real source-scoped script must block on its included source');
const realImplicitPath = rules.find(({trigger:t}) =>
 t['resource-type']?.includes('script') && !t['load-type'] &&
 (t['if-top-url'] || t['unless-top-url']) && t['url-filter']?.includes('\\/'));
assert(realImplicitPath, 'Expected a real-list implicit path/script rule in the bounded native budget');
for (const url of ['https://analytics.s3.amazonaws.com/', 'https://click.googleanalytics.com/']) {
 assert.equal(decision(url, 'https://ordinary-news.invalid/', 'script'), 'block', 'New supplement must block cross-site script: ' + url);
 assert.equal(decision(url, 'https://ordinary-news.invalid/', 'raw'), 'block', 'New supplement must block cross-site fetch: ' + url);
 assert.notEqual(decision(url, undefined, 'document'), 'block', 'New supplement must not block navigation: ' + url);
}
for(const {host,sites} of supplemental) {
 const url='https://'+host+'/';
 for(const type of ['script','raw','fetch']) {
  assert.equal(decision(url,'https://paileactivist.github.io/toolz/adblock.html',type),'block',host+' '+type);
  assert.equal(decision(url,'https://ordinary-news.invalid/',type),'block','Must not depend on the tester site: '+host);
  for(const site of sites)assert.notEqual(decision(url,'https://www.'+site+'/',type),'block','Own service must remain usable: '+host+' from '+site);
 }
 assert.notEqual(decision(url,undefined,'document'),'block','Direct navigation: '+host);
}
console.log('PASS: all 14 supplemental endpoints block cross-site resources and preserve own-service/navigation safety; Google tag, Hotjar, Yandex, new S3/Google Analytics hosts and prior exception controls pass. No network requests made.');
